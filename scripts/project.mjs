import { execFileSync } from "node:child_process";
import { existsSync, lstatSync, readdirSync } from "node:fs";
import path from "node:path";

const instructionFiles = ["AGENTS.md", "CLAUDE.md"];

function git(directory, args) {
  try {
    return execFileSync("git", ["-C", directory, ...args], { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return null;
  }
}

function getDefaultBranch(directory) {
  const head = git(directory, ["symbolic-ref", "--quiet", "--short", "refs/remotes/origin/HEAD"]);
  if (head) return head.replace(/^origin\//u, "");
  return ["main", "master"].find((branch) => git(directory, ["show-ref", "--verify", "--quiet", `refs/remotes/origin/${branch}`]) !== null) ?? null;
}

/** Removes credentials from a git remote URL. */
export function formatRemote(remote) {
  if (!remote) return null;
  const clean = remote.replace(/^(https?:\/\/)[^/@]+@/u, "$1");
  const github = clean.match(/^(?:https?:\/\/|ssh:\/\/git@|git@)github\.com[/:]([^/]+)\/([^/]+?)(?:\.git)?\/?$/u);
  return github ? { name: `${github[1]}/${github[2]}`, url: `https://github.com/${github[1]}/${github[2]}` } : { name: clean, url: null };
}

/** Lists the git repositories directly inside a project folder; worktrees and plain folders are skipped. */
export function getRepos(projectDirectory) {
  return readdirSync(projectDirectory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && !entry.name.startsWith("."))
    .map((entry) => path.join(projectDirectory, entry.name))
    .filter((directory) => lstatSync(path.join(directory, ".git"), { throwIfNoEntry: false })?.isDirectory())
    .sort()
    .map((directory) => ({
      folder: path.basename(directory),
      remote: formatRemote(git(directory, ["remote", "get-url", "origin"])),
      branch: getDefaultBranch(directory),
      instructions: instructionFiles.filter((file) => existsSync(path.join(directory, file))),
    }));
}

function formatRepoRow(repo) {
  const remote = !repo.remote ? "local only" : repo.remote.url ? `[${repo.remote.name}](${repo.remote.url})` : `\`${repo.remote.name}\``;
  const branch = repo.branch ? `\`${repo.branch}\`` : "unknown";
  const instructions = repo.instructions.length ? repo.instructions.map((file) => `\`${repo.folder}/${file}\``).join(", ") : "none";
  return `| \`${repo.folder}/\` | ${remote} | ${branch} | ${instructions} |`;
}

/** Renders a project folder's AGENTS.md from its Notion project and local repositories. */
export function renderProjectAgents({ name, url, instructions, repos }) {
  const lines = [
    `# ${name}`,
    "",
    "Generated by hellogafaro-agents from Notion. Edit the project's \"Agent instructions\" page in Notion, never this file.",
    "",
    `Notion project: ${url}. Business facts, IDs, billing and contacts live there; read it instead of copying it here.`,
    "",
    "## Repositories",
    "",
  ];

  if (repos.length === 0) {
    lines.push("No repositories are cloned in this folder yet.");
  } else {
    lines.push(
      "This project is a folder of repositories, one subfolder each. Work in the repository you are changing unless the task spans repositories. Before reading or changing files in a repository, read its own instruction files listed below; they add to and override these.",
      "",
      "| Folder | Repository | Default branch | Instructions |",
      "|---|---|---|---|",
      ...repos.map(formatRepoRow),
      "",
      "Pull requests target each repository's default branch. Organization rules (approvals, proof, Notion tasks) are in the global instructions and apply here unchanged.",
    );
  }

  lines.push("", "## Instructions", "", instructions?.trim() || "This project has no \"Agent instructions\" page in Notion yet.");
  return `${lines.join("\n")}\n`;
}
