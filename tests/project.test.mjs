import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";

import { formatRemote, getRepos, renderProjectAgents } from "../scripts/project.mjs";

const gitEnv = { ...process.env, GIT_CONFIG_GLOBAL: "/dev/null", GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@t", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@t" };

function makeRepo(directory, remote, branch) {
  mkdirSync(directory, { recursive: true });
  const git = (...args) => execFileSync("git", ["-C", directory, ...args], { env: gitEnv });
  git("init", "-q");
  git("commit", "-q", "--allow-empty", "-m", "init");
  if (remote) git("remote", "add", "origin", remote);
  if (branch) {
    git("update-ref", `refs/remotes/origin/${branch}`, "HEAD");
    git("symbolic-ref", "refs/remotes/origin/HEAD", `refs/remotes/origin/${branch}`);
  }
}

test("strips credentials and recognises GitHub remotes", () => {
  assert.deepEqual(formatRemote("https://x-access-token:secret@github.com/acme/site.git"), { name: "acme/site", url: "https://github.com/acme/site" });
  assert.deepEqual(formatRemote("git@github.com:acme/site.git"), { name: "acme/site", url: "https://github.com/acme/site" });
  assert.deepEqual(formatRemote("https://user:secret@gitlab.com/acme/site.git"), { name: "https://gitlab.com/acme/site.git", url: null });
  assert.equal(formatRemote(null), null);
});

test("lists only real repositories with their default branch and instruction files", () => {
  const root = mkdtempSync(path.join(os.tmpdir(), "agents-project-"));
  try {
    makeRepo(path.join(root, "theme"), "https://github.com/acme/theme.git", "master");
    makeRepo(path.join(root, "app"), "git@github.com:acme/app.git", null);
    makeRepo(path.join(root, "local"), null, null);
    writeFileSync(path.join(root, "theme/AGENTS.md"), "x");
    writeFileSync(path.join(root, "theme/CLAUDE.md"), "x");
    mkdirSync(path.join(root, "worktree"));
    writeFileSync(path.join(root, "worktree/.git"), "gitdir: elsewhere");
    mkdirSync(path.join(root, "design"));
    mkdirSync(path.join(root, ".agents"));

    assert.deepEqual(getRepos(root), [
      { folder: "app", remote: { name: "acme/app", url: "https://github.com/acme/app" }, branch: null, instructions: [] },
      { folder: "local", remote: null, branch: null, instructions: [] },
      { folder: "theme", remote: { name: "acme/theme", url: "https://github.com/acme/theme" }, branch: "master", instructions: ["AGENTS.md", "CLAUDE.md"] },
    ]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

test("renders the project AGENTS.md", () => {
  const output = renderProjectAgents({
    name: "Acme",
    url: "https://app.notion.com/p/Acme-1",
    instructions: "1. Be kind.\n",
    repos: [
      { folder: "theme", remote: { name: "acme/theme", url: "https://github.com/acme/theme" }, branch: "main", instructions: ["AGENTS.md"] },
      { folder: "local", remote: null, branch: null, instructions: [] },
    ],
  });
  assert.equal(
    output,
    [
      "# Acme",
      "",
      'Generated by hellogafaro-agents from Notion. Edit the project\'s "Agent instructions" page in Notion, never this file.',
      "",
      "Notion project: https://app.notion.com/p/Acme-1. Business facts, IDs, billing and contacts live there; read it instead of copying it here.",
      "",
      "## Repositories",
      "",
      "This project is a folder of repositories, one subfolder each. Work in the repository you are changing unless the task spans repositories. Before reading or changing files in a repository, read its own instruction files listed below; they add to and override these.",
      "",
      "| Folder | Repository | Default branch | Instructions |",
      "|---|---|---|---|",
      "| `theme/` | [acme/theme](https://github.com/acme/theme) | `main` | `theme/AGENTS.md` |",
      "| `local/` | local only | unknown | none |",
      "",
      "Pull requests target each repository's default branch. Organization rules (approvals, proof, Notion tasks) are in the global instructions and apply here unchanged.",
      "",
      "## Instructions",
      "",
      "1. Be kind.",
      "",
    ].join("\n"),
  );
});

test("renders a project without repositories or instructions", () => {
  const output = renderProjectAgents({ name: "Empty", url: "https://app.notion.com/p/Empty-2", instructions: null, repos: [] });
  assert.match(output, /No repositories are cloned in this folder yet\./u);
  assert.match(output, /This project has no "Agent instructions" page in Notion yet\.\n$/u);
});
